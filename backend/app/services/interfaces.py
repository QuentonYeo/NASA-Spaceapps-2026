from typing import Protocol
from app.domain.models import Exposure, Region
from app.services.rendering import PreviewPixels


class Archive(Protocol):
    def discover(self, region: Region) -> list[Exposure]: ...


class Cutouts(Protocol):
    def fetch(self, exposure: Exposure, region: Region) -> bytes: ...


class Renderer(Protocol):
    def prepare(self, cutout: bytes, region: Region | None = None, *,
                crop_cached: bool = False) -> PreviewPixels: ...
    def preview(self, pixels: PreviewPixels, shared: tuple[float, float] | None = None) -> dict: ...


class Frames(Protocol):
    def auto_observation(self, sequence_id: str, *, start: bool = False, rerun: bool = False) -> dict: ...

    def gaia_sources(self, sequence_id: str) -> dict: ...
    def start(self, region: Region, *, exposure_ids: list[str] | None = None, detector: str | None = None, find_movers: bool = False) -> dict: ...
    def poll(self, sequence_id: str, after: int) -> dict: ...
    def next_batch(self, sequence_id: str, after: int) -> dict: ...
